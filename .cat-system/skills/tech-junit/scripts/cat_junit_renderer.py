#!/usr/bin/env python3
"""Render a bounded CAT v2 case set as JUnit Jupiter source.

CAT compilation/selection owns the cases and oracles. This technology renderer
supports only required boolean/enum/integer/string-free scalar transport;
unsupported semantics must be refused, never approximated.
"""
from __future__ import annotations

import hashlib
import json
import re


_IDENT = re.compile(r"[A-Za-z_$][A-Za-z0-9_$]*\Z")
_FQCN = re.compile(r"[A-Za-z_$][A-Za-z0-9_$]*(?:\.[A-Za-z_$][A-Za-z0-9_$]*)*\Z")


def _quote(text):
    if not isinstance(text, str):
        raise ValueError("JUnit string transport requires a string")
    # JSON escapes are Java-compatible for the supported BMP scalar literals;
    # reject Java Unicode-preprocessing hazards instead of changing their value.
    if any(ord(c) < 32 or ord(c) in (0x2028, 0x2029) for c in text):
        raise ValueError("JUnit renderer cannot safely encode control/line-separator characters")
    return json.dumps(text, ensure_ascii=False)


def _scalar(value):
    if value is True:
        return "Boolean.TRUE"
    if value is False:
        return "Boolean.FALSE"
    if type(value) is int:
        if not -(2**63) <= value <= 2**63 - 1:
            raise ValueError("JUnit Long transport cannot represent integer outside signed 64-bit range")
        return f"{value}L"
    if isinstance(value, str):
        return _quote(value)
    raise ValueError("JUnit scalar renderer requires non-null boolean, long or string")


def _map(values):
    if not isinstance(values, dict):
        raise ValueError("JUnit map transport requires a mapping")
    if not values:
        return "java.util.Map.of()"
    pairs = ["java.util.Map.entry(" + _quote(k) + ", " + _scalar(v) + ")"
             for k, v in sorted(values.items())]
    return "java.util.Map.ofEntries(" + ", ".join(pairs) + ")"


def render_junit(model, cases, binding):
    """Return deterministic UTF-8 Java test source; never infer a runtime adapter."""
    package = binding.get("test_package")
    name = binding.get("test_class")
    driver = binding.get("driver_class")
    if not all(isinstance(x, str) for x in (package, name, driver)):
        raise ValueError("JUnit binding requires test_package/test_class/driver_class")
    if not _FQCN.fullmatch(package) or not _IDENT.fullmatch(name) or not _FQCN.fullmatch(driver):
        raise ValueError("invalid Java package, class or explicit driver name")
    if not cases:
        raise ValueError("JUnit renderer requires at least one selected case")
    # One current Queue vector must map to a stable and distinct Java class.
    # This avoids overwriting an earlier generated test after queue-state moves.
    digest = hashlib.sha256("\0".join(c['id'] for c in cases).encode("utf-8")).hexdigest()[:12]
    class_name = (name[:-4] if name.endswith('Test') else name) + 'Case' + digest + 'Test'
    lines = [
        "// Generated by CAT from the confirmed TestModel and selected deterministic vectors.",
        "// This class must not be modified by a production-code implementer.",
        "package " + package + ";",
        "",
        "import java.util.Map;",
        "import java.util.List;",
        "import org.junit.jupiter.api.Test;",
        "import org.junit.jupiter.api.DisplayName;",
        "import static org.junit.jupiter.api.Assertions.*;",
        "",
        "final class " + class_name + " {",

        "    private record Allowed(Map<String,Object> state, Map<String,Object> output) {}",
        "    private static boolean accepts(Map<String,Object> state, Map<String,Object> output, List<Allowed> alternatives) {",
        "        return alternatives.stream().anyMatch(x -> x.state().equals(state) && x.output().equals(output));",
        "    }",
    ]
    scope = binding.get('capability_scope')
    if scope is not None:
        # These Process capabilities are deliberately OUT OF TEST SCOPE:
        # a passing scalar PI test never proves provider reading or side effects.
        declared = ('observations=' + ','.join(sorted(scope['observations']))
                    + ' actions=' + ','.join(sorted(scope['actions'])))
        lines.insert(2, '// CAPABILITIES NOT VERIFIED (PI input/output only): ' + declared)
    seen = set()
    for i, c in enumerate(cases, 1):
        if c['id'] in seen:
            raise ValueError("duplicate CAT case ID")
        seen.add(c['id'])
        if 'output_operation' in c:
            raise ValueError("JUnit renderer cannot transmit output operation identity")
        allowed = c.get('allowed')
        if not isinstance(allowed, list) or not allowed:
            raise ValueError("CAT case lacks allowed outcomes")
        alternatives = ", ".join("new Allowed(" + _map(a['state']) + ", " + _map(a['output']) + ")" for a in allowed)
        lines.extend([
            "",
            "    @Test",
            "    @DisplayName(" + _quote(c['id']) + ")",
            "    public void catCase" + str(i).zfill(4) + "() throws Exception {",
            "        // Source TCE: " + c['source_tce'],
            "        " + driver + " driver = new " + driver + "();",
            "        Map<String,Object> pre = " + _map(c['initial_state']) + ";",
            "        Map<String,Object> input = " + _map(c['input']) + ";",
            "        driver.prepare(pre, input);",
            "        assertEquals(pre, driver.observeState(), \"CAT precondition drift\");",
            "        Map<String,Object> output = driver.trigger(" + _quote(c['trigger']) + ", input);",
            "        Map<String,Object> after = driver.observeState();",
            "        List<Allowed> allowed = List.of(" + alternatives + ");",
            "        assertTrue(accepts(after, output, allowed), \"Observed state/output not in CAT allowed outcome set: " + c['id'] + "\");",
            "    }",
        ])
    lines.append("}")
    return "\n".join(lines) + "\n"
